const hash = value => createHash("sha256").update(value).digest("hex");
const replace = (source, before, after) => {
  if (source.split(before).length !== 2) throw new Error("ElevenLabs SDK source changed; cancellation patch refused.");
  return source.replace(before, after);
};
const helper = `// Orion cancellation bridge; generated by script/patch_elevenlabs_client.mjs.
export function abortError() { return new DOMException("Voice was stopped.", "AbortError"); }
export function throwIfAborted(signal) { if (signal?.aborted) throw abortError(); }
export function stopStream(stream) { stream?.getTracks().forEach(track => track.stop()); }
export function closeContext(context) { if (context && context.state !== "closed") void context.close().catch(() => {}); }
// Browser permission requests cannot be cancelled. Fence their completion and
// stop a late stream without ever passing it back into session setup.
export function abortable(promise, signal, lateCleanup) {
  if (!signal) return Promise.resolve(promise);
  return new Promise((resolve, reject) => {
    let settled = false;
    let aborted = false;
    const abort = () => { if (!settled) { settled = true; aborted = true; reject(abortError()); } };
    if (signal.aborted) abort();
    else signal.addEventListener("abort", abort, { once: true });
    Promise.resolve(promise).then(value => {
      signal.removeEventListener("abort", abort);
      if (aborted) { try { Promise.resolve(lateCleanup?.(value)).catch(() => {}); } catch {} return; }
      settled = true; resolve(value);
    }, error => {
      signal.removeEventListener("abort", abort);
      if (!settled) { settled = true; reject(error); }
    });
  });
}
`;

