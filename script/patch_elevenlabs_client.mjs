// Validate every input before writing any output, including an existing helper.
const writes = [];
for (const patch of patches) {
  const filename = path.join(sdk, patch.file);
  const source = await readFile(filename, "utf8");
  const digest = hash(source);
  if (digest === patch.patched) continue;
  if (digest !== patch.original && digest !== patch.previous) throw new Error(`Unsupported ElevenLabs SDK content: ${patch.file}`);
  const output = digest === patch.previous ? patch.upgrade(source) : patch.apply(source);
  if (hash(output) !== patch.patched) throw new Error(`ElevenLabs patch integrity failed: ${patch.file}`);
  writes.push([filename, output]);
}
const helperPath = path.join(sdk, "dist/utils/orionAbort.js");
try {
  const existing = await readFile(helperPath, "utf8");
  if (existing !== helper) throw new Error("Unsupported existing ElevenLabs cancellation helper.");
} catch (error) { if (error.code !== "ENOENT") throw error; }
for (const [filename, output] of writes) await writeFile(filename, output);
await writeFile(helperPath, helper);
console.log("Verified ElevenLabs SDK cancellation patch (1.36.1).");
